import assert from 'node:assert/strict';
import {validateManual, validArtifact} from './canvasArtifacts.js';
import {generationElements} from './generationPlacement.js';
const content={engine:'B',format:'openui-lang-v1',capabilities:['local-state'],payload:{version:1,title:'OpenUI normalized',blocks:[{type:'form',fields:[{label:'Name',kind:'text',value:''}]}]}};
assert.equal(validateManual(content),content);
const widget={...content,id:'widget',schema_version:1,anchor_id:'anchor',state:{'0':{values:['Alice'],submitted:false}},layout:{auto_width:false,auto_height:true}};
assert(validArtifact(widget));
assert(validArtifact({...widget,format:'kumuta-json-v1'}));
assert(!validArtifact({...widget,format:'openui-executable'}));
assert(!validArtifact({...widget,source:'root=Stack(...)'}));
assert(!validArtifact({...widget,state:{'0':{values:[false]}}}));
const elements=generationElements(content,'a'.repeat(32)+'_v1',10,20,items=>items);
assert.equal(elements.length,1);
assert.equal(elements[0].type,'rectangle');
assert(!JSON.stringify(elements).includes('OpenUI'));
assert(!JSON.stringify(elements).includes('Stack'));
const other={...widget,id:'other',anchor_id:'anchor2',state:{'0':{values:['Bob'],submitted:true}}};
assert.equal(widget.state['0'].values[0],'Alice');
assert.equal(other.state['0'].values[0],'Bob');
console.log('OpenUI normalized format, allowlist, scene anchor and isolated state passed');
